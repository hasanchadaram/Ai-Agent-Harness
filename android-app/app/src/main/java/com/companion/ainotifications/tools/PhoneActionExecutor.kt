package com.companion.ainotifications.tools

import android.Manifest
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import android.media.AudioAttributes
import android.media.RingtoneManager
import android.os.Build
import android.os.VibrationEffect
import android.os.Vibrator
import android.os.VibratorManager
import android.provider.AlarmClock
import androidx.core.app.NotificationCompat
import androidx.core.app.NotificationManagerCompat
import androidx.core.content.ContextCompat
import com.companion.ainotifications.R
import com.companion.ainotifications.ui.MainActivity

class PhoneActionExecutor(private val context: Context) {

    private val notificationManager = NotificationManagerCompat.from(context)

    companion object {
        const val CHANNEL_BRIEFINGS = "channel_ai_briefings"
        const val CHANNEL_URGENT = "channel_ai_urgent"
        private var notificationIdCounter = 1000
    }

    init {
        createNotificationChannels()
    }

    private fun createNotificationChannels() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            val briefingChannel = NotificationChannel(
                CHANNEL_BRIEFINGS,
                "AI Briefings & Summaries",
                NotificationManager.IMPORTANCE_DEFAULT
            ).apply {
                description = "Summarized information and actionable updates generated by AI"
            }

            val alarmSound = RingtoneManager.getDefaultUri(RingtoneManager.TYPE_NOTIFICATION)
            val audioAttributes = AudioAttributes.Builder()
                .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                .setUsage(AudioAttributes.USAGE_NOTIFICATION_RINGTONE)
                .build()

            val urgentChannel = NotificationChannel(
                CHANNEL_URGENT,
                "AI Urgent Alerts",
                NotificationManager.IMPORTANCE_HIGH
            ).apply {
                description = "High-priority alerts requiring immediate attention"
                enableVibration(true)
                vibrationPattern = longArrayOf(0, 300, 200, 300, 200, 500)
                setSound(alarmSound, audioAttributes)
            }

            val manager = context.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
            manager.createNotificationChannel(briefingChannel)
            manager.createNotificationChannel(urgentChannel)
        }
    }

    fun scheduleAlarm(hour: Int, minute: Int, label: String): String {
        return try {
            val intent = Intent(AlarmClock.ACTION_SET_ALARM).apply {
                putExtra(AlarmClock.EXTRA_HOUR, hour)
                putExtra(AlarmClock.EXTRA_MINUTES, minute)
                putExtra(AlarmClock.EXTRA_MESSAGE, label)
                putExtra(AlarmClock.EXTRA_SKIP_UI, true)
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            context.startActivity(intent)
            "Scheduled alarm for %02d:%02d with label '$label'".format(hour, minute)
        } catch (e: Exception) {
            "Error setting alarm: ${e.message}"
        }
    }

    fun pushSmartBriefing(title: String, summary: String, urgency: String): String {
        if (Build.VERSION.SDK_INT >= 33 && ContextCompat.checkSelfPermission(context,
                Manifest.permission.POST_NOTIFICATIONS) != PackageManager.PERMISSION_GRANTED) {
            return "Notification permission is required. Enable notifications in Android app settings."
        }
        return try {
            val intent = Intent(context, MainActivity::class.java).apply {
                flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TASK
            }
            val pendingIntent = PendingIntent.getActivity(
                context, 0, intent,
                PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT
            )

            val channelId = if (urgency.equals("high", ignoreCase = true)) CHANNEL_URGENT else CHANNEL_BRIEFINGS
            val priority = if (urgency.equals("high", ignoreCase = true)) {
                NotificationCompat.PRIORITY_HIGH
            } else {
                NotificationCompat.PRIORITY_DEFAULT
            }

            val cleanTitle = title.replace(Regex("""\*\*|\*|`"""), "")
            val cleanSummary = summary.replace(Regex("""\*\*|\*|`"""), "")

            val builder = NotificationCompat.Builder(context, channelId)
                .setSmallIcon(android.R.drawable.ic_dialog_info)
                .setContentTitle(cleanTitle)
                .setContentText(cleanSummary)
                .setStyle(NotificationCompat.BigTextStyle().bigText(cleanSummary))
                .setPriority(priority)
                .setContentIntent(pendingIntent)
                .setAutoCancel(true)

            val id = synchronized(this) { ++notificationIdCounter }
            notificationManager.notify(id, builder.build())
            "Pushed briefing notification (id=$id): $title"
        } catch (e: Exception) {
            "Error pushing notification: ${e.message}"
        }
    }

    fun triggerUrgentAlert(title: String, reason: String): String {
        // Vibrate phone with distinct urgent pattern
        vibratePhone()

        // Push high-priority heads-up notification
        pushSmartBriefing(
            title = "⚠️ URGENT: $title",
            summary = reason,
            urgency = "high"
        )
        return "Triggered urgent alert and vibration for: $title"
    }

    private fun vibratePhone() {
        try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
                val vibratorManager = context.getSystemService(Context.VIBRATOR_MANAGER_SERVICE) as VibratorManager
                val vibrator = vibratorManager.defaultVibrator
                vibrator.vibrate(
                    VibrationEffect.createWaveform(longArrayOf(0, 300, 150, 300, 150, 600), -1)
                )
            } else {
                @Suppress("DEPRECATION")
                val vibrator = context.getSystemService(Context.VIBRATOR_SERVICE) as Vibrator
                @Suppress("DEPRECATION")
                vibrator.vibrate(longArrayOf(0, 300, 150, 300, 150, 600), -1)
            }
        } catch (_: Exception) {}
    }
}
