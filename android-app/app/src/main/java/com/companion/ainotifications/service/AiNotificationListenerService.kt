package com.companion.ainotifications.service

import android.app.Notification
import android.content.pm.PackageManager
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import android.util.Log
import com.companion.ainotifications.agent.AgentHarness
import com.companion.ainotifications.data.NotificationEvent
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.launch

class AiNotificationListenerService : NotificationListenerService() {

    private val serviceScope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
    private lateinit var agentHarness: AgentHarness

    companion object {
        private const val TAG = "AiNotificationService"
        var isConnected: Boolean = false
            private set
    }

    override fun onCreate() {
        super.onCreate()
        agentHarness = AgentHarness.getInstance(applicationContext)
        Log.i(TAG, "Notification Listener Service created")
    }

    override fun onListenerConnected() {
        super.onListenerConnected()
        isConnected = true
        Log.i(TAG, "Notification Listener connected to Android OS")
    }

    override fun onListenerDisconnected() {
        super.onListenerDisconnected()
        isConnected = false
        Log.w(TAG, "Notification Listener disconnected")
    }

    override fun onNotificationPosted(sbn: StatusBarNotification?) {
        super.onNotificationPosted(sbn)
        if (sbn == null) return

        val packageName = sbn.packageName ?: return

        // 1. Prevent recursion: Ignore notifications generated by this app
        if (packageName == applicationContext.packageName) {
            return
        }

        // 2. Ignore ongoing / persistent system notifications (music player, downloads, timers)
        if (sbn.isOngoing) {
            return
        }

        // 3. Extract text content
        val extras = sbn.notification.extras ?: return
        val title = extras.getCharSequence(Notification.EXTRA_TITLE)?.toString()?.trim() ?: ""
        val text = extras.getCharSequence(Notification.EXTRA_TEXT)?.toString()?.trim()
            ?: extras.getCharSequence(Notification.EXTRA_BIG_TEXT)?.toString()?.trim()
            ?: ""

        if (title.isBlank() && text.isBlank()) {
            return
        }

        // 4. Check if package is in monitored list
        val monitored = agentHarness.prefs.monitoredPackages
        if (monitored.isNotEmpty() && !monitored.contains(packageName)) {
            Log.d(TAG, "Ignored package not in whitelist: $packageName")
            return
        }

        // 5. Resolve user-friendly app name
        val appName = try {
            val pm = applicationContext.packageManager
            val appInfo = pm.getApplicationInfo(packageName, 0)
            pm.getApplicationLabel(appInfo).toString()
        } catch (_: PackageManager.NameNotFoundException) {
            packageName
        }

        Log.d(TAG, "Captured notification from $appName")

        val event = NotificationEvent(
            id = sbn.key ?: "${packageName}_${System.currentTimeMillis()}",
            packageName = packageName,
            appName = appName,
            title = title,
            text = text,
            timestamp = sbn.postTime
        )

        // 6. Dispatch to AI Agent Harness
        serviceScope.launch {
            agentHarness.processNotification(event)
        }
    }

    override fun onDestroy() {
        super.onDestroy()
        serviceScope.cancel()
    }
}
